// Тема Nuxt UI — только токены цвета, без форка компонентов.
// Сами шкалы `uv`, `ion` и `graphite` объявлены в app/assets/css/main.css, там же объяснено,
// почему нейтраль не серая.
//
// Смысловые каналы разведены так, чтобы состояние сети читалось цветом без подписи:
//   primary   — ультрафиолет, весь интерфейс и наземные линии на глобусе;
//   success   — ion, «контакт есть»: установленное соединение, пункт с маршрутом;
//   warning   — янтарь, выбранный маршрут до шлюза (как на реальных пультах);
//   error     — роза, отсутствие маршрута и отказавший аппарат;
//   secondary — шлюз на глобусе, отличается от клиентских пунктов.
export default defineAppConfig({
  ui: {
    colors: {
      primary: 'uv',
      secondary: 'ion',
      success: 'ion',
      info: 'uv',
      warning: 'amber',
      error: 'rose',
      neutral: 'graphite'
    }
  }
})
